export const isString = (u: unknown): u is string => typeof u === "string";
export const isEmpty = (s: string): s is "" => s.length === 0;
export const isNonEmpty = (s: string): boolean => s.length > 0;
export const length = (s: string) => s.length;
export const toUpperCase = <S extends string>(s: S) => s.toUpperCase() as Uppercase<S>;
export const toLowerCase = <S extends string>(s: S) => s.toLowerCase() as Lowercase<S>;
export const capitalize = <S extends string>(s: S) => (s.charAt(0).toUpperCase() + s.slice(1)) as Capitalize<S>;
export const uncapitalize = <S extends string>(s: S) => (s.charAt(0).toLowerCase() + s.slice(1)) as Uncapitalize<S>;
export const trim = (s: string) => s.trim();
export const trimStart = (s: string) => s.trimStart();
export const trimEnd = (s: string) => s.trimEnd();
export const split = (sep: string | RegExp) => (s: string): Array<string> => s.split(sep);
export const includes = (search: string) => (s: string) => s.includes(search);
export const startsWith = (search: string) => (s: string) => s.startsWith(search);
export const endsWith = (search: string) => (s: string) => s.endsWith(search);
export const replace = (search: string | RegExp, rep: string) => (s: string) => s.replace(search, rep);
export const replaceAll = (search: string | RegExp, rep: string) => (s: string) => s.replaceAll(search, rep);
export const concat = (b: string) => (a: string) => a + b;
export const repeat = (n: number) => (s: string) => s.repeat(n);
export const linesIterator = (s: string): IterableIterator<string> => s.split(/\r?\n/)[Symbol.iterator]();
export const Order = (a: string, b: string): -1 | 0 | 1 => (a < b ? -1 : a > b ? 1 : 0);
export const Equivalence = (a: string, b: string) => a === b;
const words = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1 $2").split(/[\s_\-]+/).filter(Boolean);
export const camelToSnake = (s: string) => words(s).map((w) => w.toLowerCase()).join("_");
export const snakeToCamel = (s: string) => s.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
export const kebabToSnake = (s: string) => s.replaceAll("-", "_");
export const snakeToKebab = (s: string) => s.replaceAll("_", "-");
export const pascalToSnake = camelToSnake;
export const snakeToPascal = (s: string) => capitalize(snakeToCamel(s));
