const fileTypes = new Map<string, string>();
for (const [language, keys] of Object.entries(FILE_TYPES)) {
  for (const key of keys.split(" ")) fileTypes.set(key, language);
}

const lexerNames = new Map<string, string>();
for (const [name, aliases] of Object.entries(ALIASES)) {
  lexerNames.set(name, name);
  for (const alias of aliases.split(" ")) if (alias) lexerNames.set(alias, name);
}

const customFileTypes = new Map<string, string>();

/** Maps an extension, compound extension, or basename to a language. */
export function setCustomExtension(key: string, language: string): boolean {
  if (customFileTypes.get(key) === language) return false;
  customFileTypes.set(key, language);
  return true;
}

function lookup(key: string): string | undefined {
  return customFileTypes.get(key) ?? fileTypes.get(key);
}

function matchName(name: string): string | undefined {
  const exact = lookup(name);
  if (exact !== undefined) return exact;
  const firstDot = name.indexOf(".");
  if (firstDot >= 0 && name.indexOf(".", firstDot + 1) > 0) {
    const compound = lookup(name.slice(firstDot + 1));
    if (compound !== undefined) return compound;
  }
  const lastDot = name.lastIndexOf(".");
  return lastDot >= 0 && lastDot < name.length - 1 ? lookup(name.slice(lastDot + 1)) : undefined;
}

/** The language for a file path, or `text`. */
export function getFiletypeFromFileName(fileName: string): string {
  const slash = Math.max(fileName.lastIndexOf("/"), fileName.lastIndexOf("\\"));
  const baseName = fileName.slice(slash + 1);
  return (slash >= 0 ? lookup(fileName) : undefined) ?? matchName(baseName) ?? "text";
}

/** The canonical lexer name for a language name or alias, or undefined. */
export function lexerNameFor(language: string): string | undefined {
  return lexerNames.get(language) ?? lexerNames.get(language.trim().toLowerCase());
}

/** Whether a language (or alias) has a dedicated lexer. Plain text does not. */
export function isKnownLanguage(language: string): boolean {
  const name = lexerNameFor(language);
  return name !== undefined && name !== "text";
}

/**
 * A lexer name for a language hint, a file path, or both; the hint wins when
 * it is known. Falls back to `text`.
 */
export function resolveLanguage(
  input: string | { readonly language?: string | null; readonly path?: string | null },
): string {
  if (typeof input === "string")
    return lexerNameFor(input) ?? lexerNameFor(getFiletypeFromFileName(input)) ?? "text";
  const hinted = input.language ? lexerNameFor(input.language) : undefined;
  if (hinted !== undefined && hinted !== "text") return hinted;
  const detected = input.path ? lexerNameFor(getFiletypeFromFileName(input.path)) : undefined;
  return detected ?? hinted ?? "text";
}
